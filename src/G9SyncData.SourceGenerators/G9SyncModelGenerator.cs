using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace G9SyncData.SourceGenerators;

/// <summary>
///     Emits <c>G9SyncData.Generated.G9SyncGeneratedModel</c> (internal, one per assembly): <c>Model</c> is the built client model,
///     <c>Configure(builder)</c> adds the generated tables to a builder so hand-written tables can join them.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class G9SyncModelGenerator : IIncrementalGenerator
{
    private const string ModelBuilder = "G9SyncData.Client.Model.G9CSyncClientModelBuilder";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var tables = context.SyntaxProvider.ForAttributeWithMetadataName(
            "G9SyncData.G9AttrSyncTableAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, cancellationToken) =>
                G9SyncTableExtractor.Extract((INamedTypeSymbol)attributeContext.TargetSymbol, attributeContext.Attributes[0], cancellationToken));

        var target = context.CompilationProvider.Select(static (compilation, _) =>
            new GenerationTarget(compilation.AssemblyName ?? "Assembly", compilation.GetTypeByMetadataName(ModelBuilder) is not null));

        context.RegisterSourceOutput(tables.Collect().Combine(target), static (output, input) => Emit(output, input.Left, input.Right));
    }

    private static void Emit(SourceProductionContext output, ImmutableArray<TableModel> tables, GenerationTarget target)
    {
        if (tables.IsDefaultOrEmpty) return;
        foreach (var diagnostic in tables.SelectMany(t => t.Diagnostics)) output.ReportDiagnostic(G9SyncDiagnostics.Create(diagnostic));

        if (!target.HasClientModel)
        {
            output.ReportDiagnostic(Diagnostic.Create(G9SyncDiagnostics.MissingClient, tables[0].Location?.ToLocation()));
            return;
        }

        var valid = tables.Where(t => !t.Diagnostics.Any(d => G9SyncDiagnostics.IsError(d.Id)))
            .OrderBy(t => t.TypeName, StringComparer.Ordinal)
            .ToList();
        ReportDuplicates(output, valid, "Server", t => t.ServerTable);
        ReportDuplicates(output, valid, "Local", t => t.LocalName);

        const string ns = "global::G9SyncData.Client.Model.";
        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine("namespace G9SyncData.Generated;")
            .AppendLine()
            .AppendLine($"/// <summary>The G9SyncData client model generated from the [G9AttrSyncTable] classes of {Escape(target.AssemblyName)}.</summary>")
            .AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"G9SyncData.SourceGenerators\", \"1.0\")]")
            .AppendLine("internal static class G9SyncGeneratedModel")
            .AppendLine("{")
            .AppendLine($"    private static {ns}G9CSyncClientModel? _model;")
            .AppendLine()
            .AppendLine("    /// <summary>The built model (built once, then cached).</summary>")
            .AppendLine($"    public static {ns}G9CSyncClientModel Model => _model ??= Configure(new {ns}G9CSyncClientModelBuilder()).Build();")
            .AppendLine()
            .AppendLine("    /// <summary>Adds every generated table to <paramref name=\"builder\" />; hand-written tables may be added before or after.</summary>")
            .AppendLine($"    public static {ns}G9CSyncClientModelBuilder Configure({ns}G9CSyncClientModelBuilder builder)")
            .AppendLine("    {");

        foreach (var table in valid)
        {
            source.AppendLine($"        // {table.TypeName}")
                .AppendLine($"        builder.Table({Literal(table.ServerTable)}, {Literal(table.LocalName)}, static t => t")
                .Append($"            .Key({Literal(table.KeyColumn)}, global::G9SyncData.G9ESyncColumnType.{table.KeyType})");
            foreach (var column in table.Columns)
            {
                source.AppendLine()
                    .Append($"            .Column({Literal(column.Name)}, global::G9SyncData.G9ESyncColumnType.{column.Type}, nullable: {(column.Nullable ? "true" : "false")})");
            }

            foreach (var index in table.Indexes)
            {
                source.AppendLine()
                    .Append($"            .Index({(index.Name is null ? "null" : Literal(index.Name))}, {(index.Unique ? "true" : "false")}");
                foreach (var column in index.Columns) source.Append(", ").Append(Literal(column));
                source.Append(')');
            }

            source.AppendLine(");");
        }

        source.AppendLine("        return builder;")
            .AppendLine("    }")
            .AppendLine("}");

        output.AddSource("G9SyncGeneratedModel.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static void ReportDuplicates(SourceProductionContext output, System.Collections.Generic.List<TableModel> tables, string kind, Func<TableModel, string> name)
    {
        foreach (var group in tables.GroupBy(name, StringComparer.OrdinalIgnoreCase).Where(g => g.Count() > 1))
        {
            output.ReportDiagnostic(Diagnostic.Create(G9SyncDiagnostics.Duplicate, group.Skip(1).First().Location?.ToLocation(), kind, group.Key,
                string.Join(", ", group.Select(t => t.TypeName))));
        }
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Escape(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
